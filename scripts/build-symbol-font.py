#!/usr/bin/env python3
"""Rebuild the renamed OFL symbol subset from GNU Unifont (the font Minecraft itself falls back to for these symbols)."""
import argparse,hashlib
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools import subset
p=argparse.ArgumentParser();p.add_argument('source',type=Path,help='Unifont TTF/OTF/WOFF, e.g. @fontsource/unifont files/unifont-latin-400-normal.woff');a=p.parse_args()
font=TTFont(a.source,recalcTimestamp=False)
if font['name'].getDebugName(1)!='Unifont':raise SystemExit('Expected a GNU Unifont source face')
# Symbol blocks the CJK UI subset does not cover: punctuation/super-subscripts through Misc Symbols/Dingbats/arrows.
points=set(range(0x2070,0x2e80))
options=subset.Options();options.layout_features=[];options.drop_tables+=['GSUB','GPOS','GDEF','FFTM'];options.name_IDs=['*'];options.name_legacy=True;options.name_languages=['*']
worker=subset.Subsetter(options);worker.populate(unicodes=points);worker.subset(font)
for record in font['name'].names:
 value={1:'DisCraft Symbols',2:'Regular',3:'DisCraft Symbols Regular unifont subset',4:'DisCraft Symbols Regular',6:'DisCraftSymbols-Regular',16:'DisCraft Symbols',17:'Regular'}.get(record.nameID)
 if value is not None:record.string=value.encode(record.getEncoding())
font.flavor=None
root=Path(__file__).resolve().parents[1];target=root/'forge/src/main/resources/assets/discraft/font/symbols.ttf';font.save(target)
print('Saved renamed symbol subset:',target.name,'bytes',target.stat().st_size,'glyphs',len(font.getBestCmap()))
(root/'vendor/symbol-font').mkdir(exist_ok=True)
(root/'vendor/symbol-font/source.txt').write_text('GNU Unifont '+font['name'].getDebugName(5)+' (via @fontsource/unifont 5.3.0)\nUpstream: https://unifoundry.com/unifont/\nCopyright: '+font['name'].getDebugName(0)+'\nLicense: SIL Open Font License 1.1 (OFL.txt); upstream is dual OFL-1.1 / GPL-2.0+ with font embedding exception.\nModified/renamed: DisCraft Symbols Regular; U+2070-U+2E7F subset generated by scripts/build-symbol-font.py.\nSource SHA256: '+hashlib.sha256(a.source.read_bytes()).hexdigest()+'\nSubset SHA256: '+hashlib.sha256(target.read_bytes()).hexdigest()+'\n')

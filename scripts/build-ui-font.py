#!/usr/bin/env python3
"""Rebuild the renamed OFL UI subset from Noto Sans CJK Regular TTC, face 3 (TC)."""
import argparse,hashlib
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools import subset
p=argparse.ArgumentParser();p.add_argument('source',type=Path);a=p.parse_args()
font=TTFont(a.source,fontNumber=3,recalcTimestamp=False)
if font['name'].getDebugName(1)!='Noto Sans CJK TC' or not font['name'].getDebugName(5).startswith('Version 2.004;'):raise SystemExit('Expected the Traditional Chinese regular source face')
points=set()
for low,high in ((0x20,0x250),(0x300,0x370),(0x2000,0x2070),(0x2e80,0xa000),(0xf900,0xfb00),(0xff00,0xfff0)):
 points.update(range(low,high))
options=subset.Options();options.layout_features=[];options.drop_tables+=['GSUB','GPOS','GDEF','BASE','vhea','vmtx','VORG'];options.name_IDs=['*'];options.name_legacy=True;options.name_languages=['*']
worker=subset.Subsetter(options);worker.populate(unicodes=points);worker.subset(font)
for record in font['name'].names:
 value={1:'DisCraft UI TC',2:'Regular',3:'DisCraft UI TC Regular 2.004 subset',4:'DisCraft UI TC Regular',6:'DisCraftUITC-Regular',16:'DisCraft UI TC',17:'Regular'}.get(record.nameID)
 if value is not None:record.string=value.encode(record.getEncoding())
if 'CFF ' in font:
 cff=font['CFF '].cff;cff.fontNames=['DisCraftUITC-Regular'];top=cff.topDictIndex[0];top.FamilyName='DisCraft UI TC';top.FullName='DisCraft UI TC Regular'
root=Path(__file__).resolve().parents[1];target=root/'forge/src/main/resources/assets/discraft/font/ui.otf';font.save(target)
print('Saved renamed TC outline subset:',target.name,'bytes',target.stat().st_size,'glyphs',len(font.getBestCmap()))
(root/'vendor/ui-font/source.txt').write_text('Noto Sans CJK TC Regular 2.004, TTC face 3\nUpstream: https://github.com/notofonts/noto-cjk\nCopyright: © 2014-2021 Adobe (http://www.adobe.com/).\nLicense: SIL Open Font License 1.1 (OFL.txt).\nModified/renamed: DisCraft UI TC Regular; Unicode subset generated by scripts/build-ui-font.py.\nSource TTC SHA256: '+hashlib.sha256(a.source.read_bytes()).hexdigest()+'\nSubset SHA256: '+hashlib.sha256(target.read_bytes()).hexdigest()+'\n')
